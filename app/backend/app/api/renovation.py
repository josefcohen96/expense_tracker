@router.post("/journal/{entry_id}/photo/{slot}")
async def upload_journal_photo(
    entry_id: int,
    slot: str,
    request: Request,
    file: UploadFile = File(...),
    db_conn: sqlite3.Connection = Depends(get_db_conn),
):
    """Attach (or replace) the 'before' or 'after' photo of a journal entry."""
    _require_editor(request)
    column = JOURNAL_SLOTS.get(slot)
    if not column:
        raise HTTPException(status_code=400, detail="אפשר להעלות רק תמונת 'לפני' או 'אחרי'")

    row = _journal_entry(db_conn, entry_id)
    content = await file.read()
    try:
        ext, _mime = validate_image(content, file.filename, JOURNAL_MAX_PHOTO_MB)
    except UploadRejected as exc:
        raise HTTPException(status_code=400, detail=str(exc))

    stored_name = random_stored_name(ext)
    JOURNAL_PHOTOS_DIR.mkdir(parents=True, exist_ok=True)
    (JOURNAL_PHOTOS_DIR / stored_name).write_bytes(content)

    previous = row[column]
    db_conn.execute(
        f"UPDATE renovation_journal SET {column}=?, updated_at=CURRENT_TIMESTAMP WHERE id=?",
        (stored_name, entry_id),
    )
    db_conn.commit()
    # Only drop the old file once the new name is safely committed.
    _discard_photo(previous)
    return dict(db_conn.execute(
        "SELECT * FROM renovation_journal WHERE id=?", (entry_id,)
    ).fetchone())


@router.delete("/journal/{entry_id}/photo/{slot}")
async def delete_journal_photo(
    entry_id: int,
    slot: str,
    request: Request,
    db_conn: sqlite3.Connection = Depends(get_db_conn),
):
    _require_editor(request)
    column = JOURNAL_SLOTS.get(slot)
    if not column:
        raise HTTPException(status_code=400, detail="אפשר למחוק רק תמונת 'לפני' או 'אחרי'")

    row = _journal_entry(db_conn, entry_id)
    db_conn.execute(
        f"UPDATE renovation_journal SET {column}=NULL, updated_at=CURRENT_TIMESTAMP WHERE id=?",
        (entry_id,),
    )
    db_conn.commit()
    _discard_photo(row[column])
    return dict(db_conn.execute(
        "SELECT * FROM renovation_journal WHERE id=?", (entry_id,)
    ).fetchone())


@router.get("/journal-photos/{stored_name}")
async def get_journal_photo(stored_name: str):
    """Serve a journal photo.

    Its own path segment (not under /journal/{id}) so the name can never be
    read as an entry id, and the name itself is matched against the pattern
    random_stored_name() produces before it is joined onto a path.
    """
    if not _STORED_NAME_RE.match(stored_name):
        raise HTTPException(status_code=404, detail="התמונה לא נמצאה")
    path = JOURNAL_PHOTOS_DIR / stored_name
    if not path.is_file():
        raise HTTPException(status_code=404, detail="התמונה לא נמצאה")
    # Names are random and a file is never rewritten in place, so it can be
    # cached hard — on a phone that means the timeline scrolls without refetching.
    return FileResponse(path, headers={"Cache-Control": "private, max-age=31536000, immutable"})
