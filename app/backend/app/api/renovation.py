def _discard_photo(stored_name: Optional[str]) -> None:
    """Delete a photo file, ignoring one that is already gone.

    A failure here must never break the request that triggered it: losing the
    database row matters, a leftover file on disk does not.
    """
    if not stored_name or not _STORED_NAME_RE.match(stored_name):
        return
    try:
        (JOURNAL_PHOTOS_DIR / stored_name).unlink(missing_ok=True)
    except OSError:
        pass


